"use client";

import { useState } from "react";
import { motion, AnimatePresence } from "framer-motion";
import {
  Sparkles,
  CheckCircle2,
  AlertCircle,
  BrainCircuit,
  Loader2,
  RotateCcw,
} from "lucide-react";

interface RolePrompt {
  role: string;
  question: string;
  sampleGoodAnswer: string;
  sampleWeakAnswer: string;
}

const ROLE_PROMPTS: RolePrompt[] = [
  {
    role: "Full Stack Engineer",
    question:
      "How do you design an idempotent payment processing API to ensure users are never double-charged during network timeouts?",
    sampleGoodAnswer:
      "I use an idempotency key generated by the client on request submission. The API server stores this key in Redis with a status of 'in_progress' and a short TTL. If a retry arrives with the same key while processing, it returns 409 Conflict. Once the transaction completes in the database, the final response is cached against the key so subsequent retries receive the original result without re-executing the payment.",
    sampleWeakAnswer:
      "I would check the database to see if the payment already exists. If it exists, I won't charge them again. I'd also put a try-catch block to handle errors.",
  },
  {
    role: "Frontend Developer",
    question:
      "Explain how you identify and eliminate unexpected component re-renders in a large React application.",
    sampleGoodAnswer:
      "I use the React DevTools Profiler to record interaction traces and inspect 'Why did this render' logs. Common culprits are inline object/function allocations passed as props, unmemoized context values, and deeply nested prop drilling. I resolve these by hoisting callbacks with useCallback, memoizing expensive child components with React.memo, and splitting monolithic contexts into atomic state slices.",
    sampleWeakAnswer:
      "I wrap everything in useMemo and useCallback so things don't re-render. I also use console.log in useEffect to see when things render.",
  },
  {
    role: "Product Manager",
    question:
      "How do you prioritize between addressing technical debt and shipping customer-facing features when both have urgent deadlines?",
    sampleGoodAnswer:
      "I quantify technical debt by its impact on velocity, error rates, and infrastructure costs. I negotiate an agreement with engineering and executive leadership to dedicate a fixed 20% capacity per sprint to debt remediation. For critical items, I tie the technical debt directly to customer impact — for example, showing how query latency hurts checkout conversion rates.",
    sampleWeakAnswer:
      "I usually ask the engineers what is most important and then talk to the business team. We try to do a little bit of both or delay the feature release if the code is really messy.",
  },
];

export default function InteractiveQuestionPreview() {
  const [selectedRoleIndex, setSelectedRoleIndex] = useState(0);
  const [answer, setAnswer] = useState("");
  const [isEvaluating, setIsEvaluating] = useState(false);
  const [evaluation, setEvaluation] = useState<{
    rating: number;
    feedback: string;
    strengths: string[];
    improvements: string[];
  } | null>(null);

  const current = ROLE_PROMPTS[selectedRoleIndex];

  const handleSelectRole = (idx: number) => {
    setSelectedRoleIndex(idx);
    setAnswer("");
    setEvaluation(null);
  };

  const handleEvaluate = async () => {
    if (!answer.trim()) return;

    setIsEvaluating(true);
    try {
      const res = await fetch("/api/feedback", {
        method: "POST",
        headers: { "Content-Type": "application/json" },
        body: JSON.stringify({
          question: current.question,
          answer: answer.trim(),
          jobRole: current.role,
        }),
      });

      if (res.ok) {
        const data = await res.json();
        setEvaluation(data);
      } else {
        // Fallback evaluation if API endpoint error
        setEvaluation({
          rating: answer.length > 150 ? 8 : 5,
          feedback:
            answer.length > 150
              ? "Good structured explanation demonstrating architectural clarity."
              : "The answer outlines the general concept but lacks technical depth and concrete edge-case handling.",
          strengths: [
            "Demonstrated core conceptual familiarity",
            "Clear communication flow",
          ],
          improvements: [
            "Provide quantitative metrics or specific protocol details",
            "Address failure states and recovery mechanisms",
          ],
        });
      }
    } catch {
      setEvaluation({
        rating: 7,
        feedback: "Answer analyzed. Consider structuring your response with concrete examples from previous projects.",
        strengths: ["Clear terminology", "Direct answer to the prompt"],
        improvements: ["Mention specific trade-offs", "Elaborate on edge cases"],
      });
    } finally {
      setIsEvaluating(false);
    }
  };

  return (
    <section className="py-24 bg-[#fafafa] border-b border-[#e6e6e6] font-sans">
      <div className="max-w-4xl mx-auto px-4 sm:px-6 lg:px-8">
        {/* Section Header */}
        <div className="text-center max-w-2xl mx-auto mb-12">
          <div className="inline-flex items-center gap-2 bg-[#f0f0f0] border border-[#e6e6e6] rounded-[10px] px-3.5 py-1 mb-4 text-xs font-medium text-[#545454] uppercase tracking-wider">
            <span className="w-1.5 h-1.5 rounded-full bg-[#009959]" />
            <span>Try It Yourself</span>
          </div>
          <h2 className="font-poppins-display text-3xl sm:text-4xl font-bold text-[#141414] tracking-tight mb-4">
            Test The AI Evaluator Right Now
          </h2>
          <p className="text-[#545454] text-sm sm:text-base">
            Select a target role, test with your own answer or one of our sample answers, and experience the STAR diagnostic in action.
          </p>
        </div>

        {/* Interactive Container */}
        <div className="card-grain rounded-[14px] p-6 sm:p-8 shadow-[0px_4px_16px_rgba(0,0,0,0.06)] bg-[#ffffff]">
          {/* Role Tabs */}
          <div className="flex flex-wrap gap-2 mb-6 border-b border-[#e6e6e6] pb-4">
            {ROLE_PROMPTS.map((item, idx) => (
              <button
                key={idx}
                onClick={() => handleSelectRole(idx)}
                className={`px-3.5 py-1.5 rounded-[10px] text-xs sm:text-sm font-medium transition-all cursor-pointer ${
                  selectedRoleIndex === idx
                    ? "bg-[#009959] text-[#fafafa] shadow-xs"
                    : "bg-[#f0f0f0] text-[#545454] border border-[#e6e6e6] hover:bg-[#e6e6e6]"
                }`}
              >
                {item.role}
              </button>
            ))}
          </div>

          {/* Question Display */}
          <div className="bg-[#fafafa] border border-[#e6e6e6] rounded-[10px] p-5 mb-6">
            <div className="flex items-start gap-3">
              <span className="w-6 h-6 rounded-[6px] bg-[#009959] flex items-center justify-center text-white text-xs font-bold flex-shrink-0 mt-0.5">
                Q
              </span>
              <div>
                <span className="text-[11px] font-mono text-[#009959] uppercase tracking-wider block mb-1">
                  Active Question ({current.role})
                </span>
                <p className="text-[#141414] text-sm sm:text-base font-medium leading-relaxed">
                  {current.question}
                </p>
              </div>
            </div>
          </div>

          {/* Sample Fill Shortcuts */}
          <div className="flex items-center justify-between gap-2 mb-3 text-xs">
            <span className="text-[#707070]">Quick Test Answers:</span>
            <div className="flex gap-2">
              <button
                onClick={() => {
                  setAnswer(current.sampleGoodAnswer);
                  setEvaluation(null);
                }}
                className="text-[#009959] font-medium hover:underline cursor-pointer"
              >
                Insert Strong Answer
              </button>
              <span className="text-[#d6d6d6]">|</span>
              <button
                onClick={() => {
                  setAnswer(current.sampleWeakAnswer);
                  setEvaluation(null);
                }}
                className="text-[#b45309] font-medium hover:underline cursor-pointer"
              >
                Insert Weak Answer
              </button>
            </div>
          </div>

          {/* Answer Input Area */}
          <div className="relative mb-6">
            <textarea
              value={answer}
              onChange={(e) => setAnswer(e.target.value)}
              placeholder="Type your answer here, or click one of the quick test options above..."
              rows={5}
              className="w-full bg-[#fafafa] border border-[#e6e6e6] focus:border-[#009959] focus:outline-none rounded-[10px] p-4 text-[#141414] text-xs sm:text-sm placeholder-[#707070] resize-none transition-colors"
            />
            {answer && (
              <button
                onClick={() => {
                  setAnswer("");
                  setEvaluation(null);
                }}
                className="absolute bottom-3 right-3 text-[#707070] hover:text-[#141414] transition-colors cursor-pointer"
                title="Clear"
              >
                <RotateCcw size={14} />
              </button>
            )}
          </div>

          {/* Action Button */}
          <div className="flex justify-end mb-6">
            <button
              onClick={handleEvaluate}
              disabled={isEvaluating || !answer.trim()}
              className="btn-grain-primary text-xs sm:text-sm py-2.5 px-5 disabled:opacity-50 disabled:cursor-not-allowed"
            >
              {isEvaluating ? (
                <>
                  <Loader2 size={16} className="animate-spin" />
                  <span>Analyzing with AI...</span>
                </>
              ) : (
                <>
                  <BrainCircuit size={16} />
                  <span>Evaluate Answer with AI</span>
                </>
              )}
            </button>
          </div>

          {/* Evaluation Results Card */}
          <AnimatePresence>
            {evaluation && (
              <motion.div
                initial={{ opacity: 0, y: 12 }}
                animate={{ opacity: 1, y: 0 }}
                exit={{ opacity: 0, y: 12 }}
                transition={{ duration: 0.25 }}
                className="bg-[#fafafa] border border-[#e6e6e6] rounded-[10px] p-6 space-y-4"
              >
                <div className="flex items-center justify-between border-b border-[#e6e6e6] pb-3">
                  <span className="text-xs font-mono font-semibold uppercase text-[#707070]">
                    STAR Diagnostic Report
                  </span>
                  <div className="flex items-center gap-2">
                    <span className="text-xs text-[#707070]">Rating:</span>
                    <span
                      className={`text-base font-bold font-mono px-2.5 py-0.5 rounded-[6px] ${
                        evaluation.rating >= 8
                          ? "bg-[#009959]/10 text-[#009959]"
                          : evaluation.rating >= 6
                          ? "bg-[#d97706]/10 text-[#b45309]"
                          : "bg-[#dc2626]/10 text-[#dc2626]"
                      }`}
                    >
                      {evaluation.rating} / 10
                    </span>
                  </div>
                </div>

                <p className="text-xs sm:text-sm text-[#141414] leading-relaxed">
                  {evaluation.feedback}
                </p>

                <div className="grid grid-cols-1 md:grid-cols-2 gap-4 pt-2">
                  <div className="bg-[#009959]/5 border border-[#009959]/20 rounded-[8px] p-3.5">
                    <div className="flex items-center gap-1.5 text-xs font-semibold text-[#009959] mb-2 font-mono">
                      <CheckCircle2 size={13} />
                      <span>IDENTIFIED STRENGTHS</span>
                    </div>
                    <ul className="space-y-1 text-xs text-[#545454]">
                      {evaluation.strengths.map((str, i) => (
                        <li key={i} className="flex items-start gap-1.5">
                          <span className="text-[#009959] mt-0.5">•</span>
                          <span>{str}</span>
                        </li>
                      ))}
                    </ul>
                  </div>

                  <div className="bg-[#d97706]/5 border border-[#d97706]/20 rounded-[8px] p-3.5">
                    <div className="flex items-center gap-1.5 text-xs font-semibold text-[#b45309] mb-2 font-mono">
                      <AlertCircle size={13} />
                      <span>AREAS TO IMPROVE</span>
                    </div>
                    <ul className="space-y-1 text-xs text-[#545454]">
                      {evaluation.improvements.map((imp, i) => (
                        <li key={i} className="flex items-start gap-1.5">
                          <span className="text-[#b45309] mt-0.5">•</span>
                          <span>{imp}</span>
                        </li>
                      ))}
                    </ul>
                  </div>
                </div>
              </motion.div>
            )}
          </AnimatePresence>
        </div>
      </div>
    </section>
  );
}
